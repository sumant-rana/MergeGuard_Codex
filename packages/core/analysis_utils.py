import re
from fnmatch import fnmatch
from pathlib import PurePosixPath
from typing import Any


RISK_KEYWORDS = [
    "auth",
    "authorize",
    "token",
    "payment",
    "billing",
    "refund",
    "charge",
    "pii",
    "email",
    "sql",
    "migration",
    "retry",
    "timeout",
    "prompt",
    "secret",
    "agent",
    "webhook",
]

SOURCE_SUFFIXES = {".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"}
TEST_MARKERS = ("/test/", "/tests/", "/__tests__/", ".test.", ".spec.", "_test.py")
PROMPT_PATTERNS = ("prompts/**", "agents/**", "**/*.prompt.md", "**/*.prompt", "**/*.jinja", "**/*.tmpl")
GENERATED_PATTERNS = (
    "*.lock",
    "*.snap",
    "dist/**",
    "build/**",
    "**/__generated__/**",
    "**/*.min.js",
    "**/*.gen.*",
    "**/*_pb2.py",
    "**/*_pb2.pyi",
    "**/*.pb.go",
    "**/routeTree.gen.*",
)

# Header markers commonly inserted by code generators (only checked against the
# first ~1 KB of file content). Catches generated files whose path doesn't match
# the patterns above — e.g. a vendored proto bundle or a hand-named .ts file
# carrying an `@generated` banner.
GENERATED_HEADER_RE = re.compile(
    r"(?:auto[-\s]?generated|code\s+generated\s+by|do\s+not\s+edit|@generated)",
    re.IGNORECASE,
)

# Split a string on non-letters AND on camelCase / PascalCase boundaries so
# `paymentId` -> {payment, id}, `chargeGateway` -> {charge, gateway},
# `URLPattern` -> {url, pattern}. Used to make risk-keyword matching robust
# to camelCase identifiers without devolving to substring matching (which
# tagged `_authenticated` as `auth`).
_TOKEN_SPLIT_RE = re.compile(r"[^A-Za-z]+|(?<=[a-z])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")


def normalize_path(path: str) -> str:
    return str(PurePosixPath(str(path).replace("\\", "/")))


def language_for(path: str) -> str:
    suffix = PurePosixPath(path).suffix.lower()
    return {
        ".py": "python",
        ".ts": "typescript",
        ".tsx": "typescript",
        ".js": "javascript",
        ".jsx": "javascript",
        ".md": "markdown",
        ".json": "json",
        ".yaml": "yaml",
        ".yml": "yaml",
    }.get(suffix, "unknown")


def is_generated(path: str, content: str = "") -> bool:
    """Detect auto-generated files via filename glob OR a generator header banner.

    Path patterns catch the common cases (`*.gen.*`, `*_pb2.py`, lockfiles, etc.).
    The header check catches vendored bundles and hand-named files that carry
    `@generated` / `Code generated by` / `DO NOT EDIT` banners — only the first
    1 KB is scanned to keep this cheap.
    """
    clean = normalize_path(path)
    if any(fnmatch(clean, pattern) for pattern in GENERATED_PATTERNS):
        return True
    if content and GENERATED_HEADER_RE.search(content[:1024]):
        return True
    return False


def is_test(path: str) -> bool:
    clean = f"/{normalize_path(path).lower()}"
    return any(marker in clean for marker in TEST_MARKERS)


def is_prompt(path: str) -> bool:
    clean = normalize_path(path)
    return any(fnmatch(clean, pattern) for pattern in PROMPT_PATTERNS)


def is_docs(path: str) -> bool:
    clean = normalize_path(path).lower()
    return clean.startswith("docs/") or clean.endswith((".md", ".mdx", ".rst", ".txt"))


def tokenize(text: str) -> set[str]:
    """Lower-case token set, split on non-letters AND camelCase boundaries.

    Used by ``risk_hits*`` and downstream agents (concept-classifier, inline
    anchors) so a substring of a longer identifier (the classic
    `_authenticated` matching `auth` problem) no longer fires the keyword,
    while still letting `chargeGateway` / `customerEmail` register the
    `charge` / `email` keywords they genuinely contain.
    """
    return {tok.lower() for tok in _TOKEN_SPLIT_RE.split(text) if tok}


# Back-compat alias for callers that imported the underscore-prefixed name
# while it was internal. New code should use ``tokenize``.
_tokenize = tokenize


def risk_hits(*parts: str) -> list[str]:
    """Token-aware risk match across the supplied text parts (path, patch, content).

    Kept for backwards compat with callers that pass already-narrowed text.
    Prefer ``risk_hits_in_added_lines`` for diff-driven classification —
    matching on the path alone gives false positives (e.g., flagging files
    just because they import from ``_authenticated/``).
    """
    tokens: set[str] = set()
    for part in parts:
        if part:
            tokens.update(tokenize(str(part)))
    return [keyword for keyword in RISK_KEYWORDS if keyword in tokens]


def added_patch_lines(patch: str) -> list[str]:
    """Return only the lines added in a unified diff (no ``+++``/headers)."""
    out: list[str] = []
    for raw in (patch or "").splitlines():
        if raw.startswith("+++") or raw.startswith("---") or raw.startswith("@@"):
            continue
        if raw.startswith("+"):
            out.append(raw[1:])
    return out


def risk_hits_in_added_lines(patch: str, content: str = "") -> list[str]:
    """Stricter risk match: scan only the ADDED diff lines (+ optional file content).

    Deliberately ignores the file path so a clean component file under
    ``src/routes/_authenticated/...`` doesn't get tagged "auth-touching" just
    because the directory name contains ``auth``. Likewise a UI helper that
    imports from a module named ``token-store`` won't trip "token" unless
    the helper actually writes the word ``token`` in its added lines.

    Uses token-aware matching (see ``tokenize``) so identifiers like
    ``_authenticated`` no longer match the bare ``auth`` keyword.
    """
    body = "\n".join(added_patch_lines(patch))
    if content:
        body = f"{body}\n{content}"
    if not body:
        return []
    tokens = tokenize(body)
    return [keyword for keyword in RISK_KEYWORDS if keyword in tokens]


