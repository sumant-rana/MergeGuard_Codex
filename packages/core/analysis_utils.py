def saturate_risk(raw: float, knee: float = 80.0, span: float = 40.0) -> int:
    """Map an uncapped raw risk number into the 0-100 display range.

    Linear for ``raw <= knee``, then asymptotes toward 100 with an exponential
    decay of width ``span``. Lets us preserve precision in the "normal" risk
    range while still differentiating very-high scores via the persisted raw
    value — instead of the previous hard ``min(100, x)`` cap that flattened
    every high-risk PR to the same number.

    Examples (knee=80, span=40):
        raw=40  -> 40
        raw=80  -> 80
        raw=100 -> 88
        raw=150 -> 96
        raw=400 -> 100
    """
    value = max(0.0, float(raw))
    if value <= knee:
        return int(round(value))
    headroom = max(0.0, 100.0 - knee)
    return int(round(knee + headroom * (1.0 - math.exp(-(value - knee) / max(1.0, span)))))


# File-name pairing for "did the author also touch the test for this file?"
_TEST_SUFFIX_RE = re.compile(r"\.(?:test|spec)\.[a-z]+$", re.IGNORECASE)


def has_paired_test(file_path: str, test_paths: list[str]) -> bool:
    """True iff ``test_paths`` contains a test file that plausibly covers ``file_path``.

    Matches if any test path's filename stem (after stripping ``.test``/``.spec``)
    equals the source file's stem. No AST analysis — same-stem heuristic.
    """
    clean = normalize_path(file_path)
    stem = PurePosixPath(clean).stem
    if not stem:
        return False
    for test_path in test_paths:
        if not test_path:
            continue
        norm_test = normalize_path(test_path)
        test_stem = _TEST_SUFFIX_RE.sub("", PurePosixPath(norm_test).name)
        if test_stem == stem:
            return True
    return False


# Identifiers that signal a file is "code", not static literal data.
_CODE_MARKERS_RE = re.compile(
    r"\b(?:function|class|def|async\s+def|=>\s*[{(]|await\s|return\s+[A-Za-z_(])",
)


def is_static_data_file(path: str, patch: str = "") -> bool:
    """Heuristic: the file looks like an exported literal dataset, not logic.

    Triggers when EITHER the path lives under a ``data/`` directory OR the file
    has a tabular suffix (``.json``, ``.yaml``), AND the added lines contain no
    function-shaped code markers. Used to give back a small risk credit for
    files like ``src/features/release-highlights/data/highlights.ts`` that are
    pure ``export const`` arrays.
    """
    clean = normalize_path(path).lower()
    suffix = PurePosixPath(clean).suffix
    path_signal = (
        "/data/" in f"/{clean}"
        or clean.startswith("data/")
        or "/fixtures/" in f"/{clean}"
        or suffix in {".json", ".yaml", ".yml"}
    )
    if not path_signal:
        return False
    added = "\n".join(added_patch_lines(patch))
    if not added.strip():
        # No diff hints — fall back to the path signal alone, which is already
        # restrictive (``data/`` directory or JSON/YAML suffix).
        return True
    return not _CODE_MARKERS_RE.search(added)


def important_terms(text: str) -> list[str]:
    words = re.sub(r"[^a-zA-Z0-9_/-]+", " ", text).lower().split()
    stop = {"that", "this", "with", "from", "into", "should", "must", "need", "needs", "review"}
    return [word for word in words if len(word) >= 4 and word not in stop][:16]


def extract_symbols(path: str, patch: str = "", content: str = "") -> list[dict[str, Any]]:
    source = "\n".join(part for part in [patch, content] if part)
    patterns = [
        ("class", re.compile(r"^[+\s]*(?:export\s+)?class\s+([A-Za-z_$][\w$]*)", re.M)),
        ("function", re.compile(r"^[+\s]*(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)", re.M)),
        ("function", re.compile(r"^[+\s]*(?:export\s+)?const\s+([A-Za-z_$][\w$]*)\s*=", re.M)),
        ("function", re.compile(r"^[+\s]*(?:async\s+)?def\s+([A-Za-z_][\w]*)", re.M)),
    ]
    symbols: list[dict[str, Any]] = []
    seen: set[str] = set()
    for kind, pattern in patterns:
        for match in pattern.finditer(source):
            name = match.group(1)
            key = f"{kind}:{name}"
            if key in seen:
                continue
            seen.add(key)
            symbols.append({"name": name, "kind": kind, "confidence": 0.82})
    if symbols:
        return symbols
    return [{"name": PurePosixPath(path).stem, "kind": "file", "confidence": 0.42}]


def codeowners_for(path: str, codeowners: str = "") -> list[str]:
    clean = normalize_path(path)
    matches: list[tuple[int, list[str]]] = []
    for raw in codeowners.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        pattern, *owners = line.split()
        normalized_pattern = pattern.lstrip("/")
        if normalized_pattern.endswith("/"):
            hit = clean.startswith(normalized_pattern)
        else:
            hit = fnmatch(clean, normalized_pattern) or clean.startswith(f"{normalized_pattern.rstrip('/')}/")
        if hit and owners:
            matches.append((len(normalized_pattern.replace("*", "")), owners))
    if not matches:
        return ["unassigned"]
    return sorted(matches, key=lambda item: item[0], reverse=True)[0][1]
